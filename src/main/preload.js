'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('kanki', {
  info: () => ipcRenderer.invoke('app:info'),
  ensurePermissions: () => ipcRenderer.invoke('media:ensure-permissions'),
  ensureCamera: () => ipcRenderer.invoke('media:ensure-camera'),
  openScreenSettings: () => ipcRenderer.invoke('media:open-screen-settings'),
  getSources: () => ipcRenderer.invoke('screen:get-sources'),
  selectSource: (id, audio) => ipcRenderer.invoke('screen:select-source', id, audio),
  hostServer: (opts) => ipcRenderer.invoke('server:host', opts),
  stopServer: () => ipcRenderer.invoke('server:stop'),
  serverStatus: () => ipcRenderer.invoke('server:status'),
  startTunnel: (opts) => ipcRenderer.invoke('tunnel:start', opts),
  stopTunnel: () => ipcRenderer.invoke('tunnel:stop'),
  notify: (title, body) => ipcRenderer.invoke('app:notify', title, body),
  flash: () => ipcRenderer.invoke('app:flash'),
  flashbang: () => ipcRenderer.invoke('fx:flashbang'),
  shake: () => ipcRenderer.invoke('app:shake'),
  setPtt: (keycode) => ipcRenderer.invoke('ptt:set', keycode),
  capturePttKey: () => ipcRenderer.invoke('ptt:capture'),
  onPtt: (cb) => ipcRenderer.on('ptt', (_e, down) => cb(down)),
  updateState: () => ipcRenderer.invoke('update:state'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  idleTime: () => ipcRenderer.invoke('app:idle-time'),
  // Uzaktan kontrol (yayıncı tarafı)
  rcCheck: () => ipcRenderer.invoke('rc:check'),
  rcStart: (sourceId, who) => ipcRenderer.invoke('rc:start', sourceId, who),
  rcInput: (msg) => ipcRenderer.send('rc:input', msg),
  rcStop: () => ipcRenderer.invoke('rc:stop'),
  onRcStopped: (cb) => ipcRenderer.on('rc:stopped-locally', (_e, reason) => cb(reason)),
  onUpdate: (cb) => ipcRenderer.on('update', (_e, state) => cb(state)),
  // Ek özellikler
  uploadFile: (o) => ipcRenderer.invoke('file:upload', o),
  downloadFile: (o) => ipcRenderer.invoke('file:download', o),
  scanActivity: (o) => ipcRenderer.invoke('activity:scan', o),
  setKeybinds: (list) => ipcRenderer.invoke('keys:set', list),
  onKeybind: (cb) => ipcRenderer.on('keybind', (_e, id) => cb(id)),
  overlay: (p) => ipcRenderer.send('overlay:update', p),
  showMark: (m) => ipcRenderer.invoke('mark:show', m),
  pingPick: () => ipcRenderer.invoke('ping:pick'),
  regionPick: (sourceId, editing) => ipcRenderer.invoke('region:pick', sourceId, editing),
  regionFrame: (shareId, sourceId, r) => ipcRenderer.invoke('region:frame', shareId, sourceId, r),
  // Doğrudan dosya aktarımı
  xferPick: () => ipcRenderer.invoke('xfer:pick'),
  xferRead: (key, len) => ipcRenderer.invoke('xfer:read', key, len),
  xferRelease: (key) => ipcRenderer.invoke('xfer:release', key),
  xferDest: (files) => ipcRenderer.invoke('xfer:dest', files),
  xferOpen: (dest, name, size) => ipcRenderer.invoke('xfer:open', dest, name, size),
  xferWrite: (key, data) => ipcRenderer.invoke('xfer:write', key, data),
  xferFinish: (key) => ipcRenderer.invoke('xfer:finish', key),
  xferAbort: (key) => ipcRenderer.invoke('xfer:abort', key),
  xferForget: (dest) => ipcRenderer.invoke('xfer:forget', dest),
  xferReveal: (p) => ipcRenderer.invoke('xfer:reveal', p),
  xferOpenFile: (p) => ipcRenderer.invoke('xfer:openFile', p),
  screenPing: (p) => ipcRenderer.invoke('ping:show', p),
  watchResolve: (url, maxHeight) => ipcRenderer.invoke('watch:resolve', url, maxHeight),
  readAsset: (name) => ipcRenderer.invoke('asset:read', name),
  memUsage: () => ipcRenderer.invoke('app:mem'),
  onInvite: (cb) => ipcRenderer.on('invite', (_e, p) => cb(p)),
  autotest: process.env.KANKI_AUTOTEST ? JSON.parse(process.env.KANKI_AUTOTEST) : null,
});
